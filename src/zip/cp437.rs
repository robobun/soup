//! Code page 437, which is what a name is in when its entry does not say that it is UTF-8.

/// The characters of the bytes 0x80 to 0xFF. The bytes below are ASCII.
const HIGH: [char; 128] = [
    'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å', 'É', 'æ', 'Æ',
    'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ', 'á', 'í', 'ó', 'ú', 'ñ', 'Ñ',
    'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»', '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕',
    '╣', '║', '╗', '╝', '╜', '╛', '┐', '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦',
    '╠', '═', '╬', '╧', '╨', '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐',
    '▀', 'α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩', '≡', '±',
    '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', '\u{a0}',
];

/// Appends `name` in UTF-8.
pub fn cp437_to_utf8(name: &[u8], out: &mut Vec<u8>) -> crate::Result<()> {
    // No character of the page takes more than three bytes.
    out.try_reserve(name.len().saturating_mul(3))?;
    for &byte in name {
        match HIGH.get(usize::from(byte).wrapping_sub(0x80)) {
            Some(&high) => out.extend_from_slice(high.encode_utf8(&mut [0; 4]).as_bytes()),
            None => out.push(byte),
        }
    }
    Ok(())
}
